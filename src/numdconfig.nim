## ngum-powered configuration editor shared by the numd CLI.
import std/[os, osproc, strutils, tables, parsecfg, tempfiles]
import core

const
  Sources = @["kp7", "kp8", "kp9", "kp4", "kp5", "kp6",
              "kp1", "kp2", "kp3", "kp0", "kpdot", "kpenter",
              "kpplus", "kpminus", "kpslash", "kpasterisk"]
  DefaultBindings = {
    "kp7": "super+7", "kp8": "super+8", "kp9": "super+9",
    "kp4": "super+left", "kp5": "super+up", "kp6": "super+right",
    "kp1": "super+1", "kp2": "super+2", "kp3": "super+3",
    "kp0": "ctrl+alt+t", "kpdot": "printscreen",
    "kpenter": "", "kpplus": "", "kpminus": "", "kpslash": "", "kpasterisk": ""
  }.toTable

proc ngumExecutable(): string =
  result = findExe("ngum")
  if result.len == 0 and fileExists("/usr/lib/numd/ngum"):
    result = "/usr/lib/numd/ngum"

proc runPrompt(args: varargs[string]): string =
  let (tempFile, tmp) = createTempFile("numd-ngum-", ".out")
  tempFile.close()
  let executable = ngumExecutable()
  var argv = @["/bin/sh", "-c", quoteShell(executable) & " \"$@\" > " & quoteShell(tmp), "ngum"]
  for arg in args: argv.add(arg)
  let process = startProcess(argv[0], args = argv[1..^1],
                             options = {poUsePath, poParentStreams})
  let status = process.waitForExit()
  process.close()
  if status != 0 or not fileExists(tmp):
    try: removeFile(tmp)
    except OSError: discard
    return ""
  result = strutils.strip(readFile(tmp))
  removeFile(tmp)

proc runConfirm(args: varargs[string]): bool =
  var argv = @[ngumExecutable()]
  for arg in args: argv.add(arg)
  let process = startProcess(argv[0], args = argv[1..^1],
                             options = {poUsePath, poParentStreams})
  result = process.waitForExit() == 0
  process.close()

proc heading(text: string) =
  stderr.writeLine(text)

proc renderConfig(device: string, bindings: Table[string, string]): string =
  result = "# Generated by numd config; edit with `numd config`.\n" &
           "# Hold Num Lock + numpad key to send the shortcut.\n\n" &
           "[device]\npath = " & device & "\n\n[bindings]\n"
  for key in Sources:
    let chord = bindings.getOrDefault(key)
    if chord.len > 0: result.add(key & " = \"" & chord & "\"\n")

proc writeConfig(path, device: string, bindings: Table[string, string]) =
  let tmp = path & ".tmp"
  writeFile(tmp, renderConfig(device, bindings))
  moveFile(tmp, path)

proc runTui*(target: string): bool =
  ## Edit config; true iff saved. Escape/Discard leaves the file untouched.
  if ngumExecutable().len == 0:
    raise newException(IOError, "`ngum` is missing; reinstall the numd package")

  heading("numd config — " & target)
  var bindings = DefaultBindings
  var device = "auto"
  if fileExists(target):
    let cfg = loadConfig(target)
    for key in Sources:
      bindings[key] = cfg.getSectionValue("bindings", key, DefaultBindings[key])
    device = cfg.getSectionValue("device", "path", "auto").strip()

  const Save = "Save & exit"
  const Discard = "Discard changes"
  while true:
    var items = @["device  ->  " & device]
    for key in Sources:
      let chord = bindings.getOrDefault(key)
      items.add(key & "  ->  " & (if chord.len > 0: chord else: "(unset)"))
    items.add(Save)
    items.add(Discard)

    var argv = @["choose", "--header", "numd config — " & target]
    for item in items: argv.add(item)
    let picked = runPrompt(argv)
    if picked.len == 0:
      stderr.writeLine("cancelled; nothing written")
      return false
    if picked == Save:
      if not runConfirm("--header", "Write " & target & "?"): continue
      writeConfig(target, device, bindings)
      heading("saved " & target)
      return true
    if picked == Discard:
      stderr.writeLine("discarded")
      return false

    let key = if picked.startsWith("device"): "device" else: picked.split(" ")[0]
    let current = if key == "device": device else: bindings.getOrDefault(key)
    let label = if current.len > 0: current else: "(unset)"
    let value = runPrompt("input", "--header", key & " — Enter keeps, Escape cancels",
                          "--value", label, "--placeholder", "e.g. super+7")
    if value.len == 0: continue
    if value == "(unset)":
      if key == "device": device = "auto"
      else: bindings[key] = ""
      continue
    if key != "device":
      try: discard parseChord(value)
      except CatchableError as error:
        stderr.writeLine("invalid binding: " & error.msg & " (kept " & label & ")")
        continue
    if key == "device": device = value
    else: bindings[key] = value

when isMainModule:
  try:
    discard runTui(if paramCount() > 0: paramStr(1) else: "/etc/numd/config.ini")
  except CatchableError as error:
    stderr.writeLine("numd config: " & error.msg)
    quit(1)
