## numd-config — small ngum-powered TUI that writes /etc/numd/config.ini.
## Prompts come from the ngum CLI (UI on stderr, values on stdout); each
## binding is validated with core.parseChord before anything is written.
import std/[os, osproc, strutils, tables, parsecfg]
import ngum/gloss/style
import ngum/gloss/color
import core

const
  Sources = @["kp7", "kp8", "kp9", "kp4", "kp5", "kp6",
              "kp1", "kp2", "kp3", "kp0", "kpdot", "kpenter",
              "kpplus", "kpminus", "kpslash", "kpasterisk"]
  Defaults = {
    "kp7": "super+7", "kp8": "super+8", "kp9": "super+9",
    "kp4": "super+left", "kp5": "super+up", "kp6": "super+right",
    "kp1": "super+1", "kp2": "super+2", "kp3": "super+3",
    "kp0": "ctrl+alt+t", "kpdot": "printscreen",
    "kpenter": "", "kpplus": "", "kpminus": "", "kpslash": "", "kpasterisk": ""
  }.toTable

proc runPrompt(args: varargs[system.string]): system.string =
  ## Run an ngum prompt: UI stays on the terminal (stderr), value comes back
  ## through a temp file holding ngum's stdout.
  let tmp = getTempDir() / "numd-ngum-" & $getCurrentProcessId() & ".out"
  var script = "ngum \"$@\" > " & quoteShell(tmp)
  var argv = @["/bin/sh", "-c", script, "ngum"]
  for a in args: argv.add(a)
  let p = startProcess(argv[0], args = argv[1..^1],
                       options = {poUsePath, poParentStreams})
  let status = p.waitForExit()
  p.close()
  if status != 0 or not fileExists(tmp):
    try: removeFile(tmp)
    except OSError: discard
    return ""
  result = strutils.strip(readFile(tmp))
  removeFile(tmp)

proc runConfirm(args: varargs[system.string]): bool =
  ## ngum confirm signals yes via exit status 0, no via 1; no stdout output.
  var argv = @["ngum"]
  for a in args: argv.add(a)
  let p = startProcess(argv[0], args = argv[1..^1],
                       options = {poUsePath, poParentStreams})
  let status = p.waitForExit()
  p.close()
  result = status == 0

proc heading(text: system.string) =
  let s = newStyle().foreground(parseColor("cyan")).bold()
  stderr.writeLine(render(s, text))

proc renderConfig(device: system.string, bindings: Table[system.string, system.string]): system.string =
  result = "# Generated by numd-config; edit with 'numd-config'.\n" &
           "# Hold Num Lock + numpad key to send the shortcut.\n\n" &
           "[device]\npath = " & device & "\n\n[bindings]\n"
  for key in Sources:
    let chord = bindings.getOrDefault(key)
    if chord.len > 0: result.add(key & " = \"" & chord & "\"\n")

proc writeConfig(path, device: system.string, bindings: Table[system.string, system.string]) =
  let tmp = path & ".tmp"
  writeFile(tmp, renderConfig(device, bindings))
  moveFile(tmp, path)

when isMainModule:
  let target = if paramCount() > 0: paramStr(1) else: "/etc/numd/config.ini"
  heading("numd config — " & target)

  # Load existing values so the TUI starts from what is configured.
  var bindings = Defaults
  if fileExists(target):
    try:
      let cfg = loadConfig(target)
      for key in Sources:
        bindings[key] = cfg.getSectionValue("bindings", key, Defaults[key])
    except CatchableError:
      discard

  var device = "auto"
  if fileExists(target):
    try:
      let cfg = loadConfig(target)
      device = cfg.getSectionValue("device", "path", "auto").strip()
    except CatchableError:
      discard

  const Save = "Save & exit"
  const Discard = "Discard changes"
  while true:
    var items: seq[system.string] = @["device  ->  " & device]
    for key in Sources:
      let chord = bindings.getOrDefault(key)
      items.add(key & "  ->  " & (if chord.len > 0: chord else: "(unset)"))
    items.add(Save)
    items.add(Discard)

    var argv = @["choose", "--header", "numd config — " & target]
    for item in items: argv.add(item)
    let picked = runPrompt(argv)
    if picked.len == 0: # Escape / cancel
      stderr.writeLine("cancelled; nothing written")
      quit(1)

    if picked == Save:
      if runConfirm("--header", "Write " & target & "?"):
        try:
          writeConfig(target, device, bindings)
          heading("saved " & target)
        except CatchableError as e:
          stderr.writeLine("failed to write " & target & ": " & e.msg &
                           "\nTry: sudo numd-config " & target)
          quit(1)
      break
    if picked == Discard:
      stderr.writeLine("discarded")
      break

    let key = if picked.startsWith("device"): "device" else: picked.split(" ")[0]
    let current = if key == "device": device else: bindings.getOrDefault(key)
    let label = if current.len > 0: current else: "(unset)"
    let value = runPrompt("input", "--header", key & " — Enter keeps, Escape cancels",
                          "--value", label, "--placeholder", "e.g. super+7")
    if value.len == 0: continue # cancel keeps current value
    if value == "(unset)":
      if key == "device": device = "auto"
      else: bindings[key] = ""
      continue
    if key != "device":
      try:
        discard parseChord(value)
      except CatchableError as e:
        stderr.writeLine("invalid binding: " & e.msg & " (kept " & label & ")")
        continue
    if key == "device": device = value
    else: bindings[key] = value
